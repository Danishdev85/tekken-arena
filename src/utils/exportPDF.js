import { gameLabel, getCharacter } from './roster';
import { computeStandings } from '../engine/ranking';

function playerName(t, id) {
  const p = (t.players || []).find((x) => x.id === id);
  return p ? p.name : 'Unknown';
}

function charName(t, id) {
  const c = id ? getCharacter(t.game, id) : null;
  return c ? c.name : '—';
}

/** Download a results PDF: champion, final standings and match results. */
export async function downloadResultsPDF(tournament) {
  const { jsPDF } = await import('jspdf');
  const doc = new jsPDF();
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  let y = 18;
  const line = (text, size = 11, bold = false, gap = 6) => {
    if (y > pageHeight - 16) {
      doc.addPage();
      y = 18;
    }
    doc.setFont('helvetica', bold ? 'bold' : 'normal');
    doc.setFontSize(size);
    doc.text(String(text), 14, y);
    y += gap;
  };

  doc.setFillColor(9, 9, 11);
  doc.rect(0, 0, pageWidth, 30, 'F');
  doc.setTextColor(249, 115, 22);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(18);
  doc.text('TEKKEN ARENA', 14, 13);
  doc.setTextColor(244, 244, 245);
  doc.setFontSize(12);
  doc.text(tournament.name, 14, 22);
  doc.setTextColor(20, 20, 20);
  y = 40;

  line(`Game: ${gameLabel(tournament.game)}`, 11, true);
  line(`Players: ${tournament.players.length}`, 11);
  line(`Total matches: ${tournament.matches.length} (${tournament.matches.filter((m) => m.winnerId).length} completed)`, 11);
  y += 2;

  if (tournament.championId) {
    line(`CHAMPION: ${playerName(tournament, tournament.championId)}`, 14, true, 8);
  }

  const league = tournament.matches.filter((m) => m.phase === 'league');
  const tiebreak = tournament.matches.filter((m) => m.phase === 'tiebreak');
  const standings = computeStandings(tournament.players, league, tiebreak);
  line('FINAL STANDINGS', 13, true, 7);
  line('Rank  Player            P    W    L    Win%   Pts', 10, true, 5);
  for (const r of standings) {
    const pct = `${Math.round(r.winPct * 100)}%`;
    line(
      `${String(r.rank).padEnd(5)} ${r.name.padEnd(17)} ${String(r.played).padEnd(4)} ${String(r.wins).padEnd(4)} ${String(r.losses).padEnd(4)} ${pct.padEnd(6)} ${r.points}`,
      10, false, 5,
    );
  }
  y += 3;
  line('MATCH RESULTS', 13, true, 7);
  for (const m of tournament.matches) {
    const phaseLabel =
      m.phase === 'league' ? `R${m.round} M${m.number}` :
      m.phase === 'tiebreak' ? `Decider ${m.number}` :
      m.phase === 'semifinal' ? m.label || 'Semifinal' : 'Grand Final';
    const result = m.winnerId ? `Winner: ${playerName(tournament, m.winnerId)}` : 'Not played';
    line(
      `${phaseLabel}: ${playerName(tournament, m.player1Id)} (${charName(tournament, m.char1Id)}) vs ${playerName(tournament, m.player2Id)} (${charName(tournament, m.char2Id)}) — ${result}`,
      9, false, 5,
    );
  }
  y += 4;
  line('Generated by TEKKEN ARENA — fan-made tournament tool. Not affiliated with Bandai Namco.', 8);

  doc.save(`${tournament.name.replace(/[^a-z0-9]+/gi, '-').toLowerCase()}-results.pdf`);
}
